<?php

namespace App\Services\Pattern\Generators;

/**
 * ژنراتوری که یک *خانواده* از مدل‌هاست، نه یک مدل.
 *
 * تا این‌جا هر مدلِ کاتالوگ یک کلاس بود، و برای مدل‌هایی که واقعاً درفتِ خودشان
 * را دارند همین درست است. ولی خیلی از مدل‌های یک خانواده هیچ کدِ تازه‌ای
 * نمی‌آورند و فقط یک ردیفِ داده‌اند: «پیراهن راسته، قد ۶۰، آستین کوتاه، یقهٔ
 * گرد». نوشتنِ هزار کلاسِ بیست‌خطی برای هزار ردیفِ داده، کاتالوگ را بزرگ نمی‌کند
 * — فقط پوشه را شلوغ می‌کند.
 *
 * پس یک کلاس می‌تواند جدولی از ردیف‌ها بدهد و رجیستری هر ردیف را یک مدلِ مستقل
 * ثبت کند. از بیرون هیچ فرقی دیده نمی‌شود: هر ردیف کلیدِ خودش، نامِ خودش،
 * پارامترهای خودش و الگوی خودش را دارد و در همان بازرسیِ سراسری هم می‌افتد.
 *
 * @method static array<string, array<string, mixed>> variants()
 */
interface VariantAware
{
    /**
     * ردیف‌های این خانواده: کلیدِ مدل ⇒ شناسنامهٔ آن.
     *
     * @return array<string, array<string, mixed>>
     */
    public static function variants(): array;

    /** نسخه‌ای از همین ژنراتور که روی یکی از ردیف‌ها تنظیم شده است. */
    public function forVariant(string $key): static;
}
