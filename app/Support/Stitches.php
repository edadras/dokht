    /** همهٔ کوک‌ها، ماشینی و دستی. */
    public static function all(): array
    {
        return ['machine' => static::MACHINE, 'hand' => static::HAND];
    }

    /** یک کوک، از هر دو فهرست. */
    public static function stitch(string $key): ?array
    {
        return static::MACHINE[$key] ?? static::HAND[$key] ?? null;
    }

    /** نامِ خواندنیِ یک کوک. */
    public static function name(string $key): string
    {
        return static::stitch($key)['name'] ?? $key;
    }

    /** ردهٔ وزنیِ پارچه. */
    public static function weightClass(float $gsm): array
    {
        foreach (static::WEIGHTS as $row) {
            if ($gsm <= $row['upto']) {
                return $row;
            }
        }

        return static::WEIGHTS[count(static::WEIGHTS) - 1];
    }

    /**
     * فاصلهٔ کوک برای این پارچه و این کوک، به میلی‌متر.
     *
     * پایه از وزنِ پارچه می‌آید و بعد در بازهٔ خودِ کوک محدود می‌شود: رودوزی
     * همیشه از درزدوزی بلندتر است و مگسی همیشه ریز.
     */
    public static function length(string $key, float $gsm): float
    {
        $stitch = static::stitch($key);

        if ($stitch === null) {
            return static::weightClass($gsm)['length'];
        }

        [$min, $best, $max] = $stitch['length'];
        $base = static::weightClass($gsm)['length'];

        /*
         * کوک‌های نما و آماده‌سازی بازهٔ خودشان را دارند و به وزن کاری ندارند؛
         * درزدوزی ولی مستقیم از وزن می‌آید. برای همین به‌جای «همیشه پیشنهادی»،
         * عددِ وزن در بازهٔ کوک فشرده می‌شود: پارچهٔ سنگین رودوزیِ درشت‌تر
         * می‌گیرد، ولی هیچ‌وقت کوتاه‌تر از کمینهٔ خودِ رودوزی نمی‌شود.
         */
        $scaled = $base * ($best / 2.5);

        return round(max($min, min($max, $scaled)), 1);
    }

    /** کوک در اینچ — واحدِ سوزن‌های صنعتی. */
    public static function perInch(float $mm): int
    {
        return $mm > 0 ? (int) round(25.4 / $mm) : 0;
    }
